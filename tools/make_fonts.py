#!/usr/bin/env python3
import struct
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

INTER = "/usr/share/fonts/opentype/inter/"
MONO = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"

ASCII = "".join(chr(c) for c in range(32, 127))
EXTRA = "°·–—→↑↓•…"
DIGITS = "0123456789"

FONTS = [
    ("F_CLOCK", INTER + "InterDisplay-Medium.otf", 40, DIGITS + ":- "),
    ("F_HUGE", INTER + "InterDisplay-Light.otf", 58, DIGITS + ":-–° "),
    ("F_BIG", INTER + "InterDisplay-SemiBold.otf", 24, DIGITS + "%+-–.: dhm"),
    ("F_TITLE", INTER + "Inter-SemiBold.otf", 14, ASCII + EXTRA),
    ("F_BODY", INTER + "Inter-Medium.otf", 12, ASCII + EXTRA),
    ("F_MONO", MONO, 9, ASCII + EXTRA),
]


def glyph(font, ch):
    empty = dict(u=ord(ch), w=1, h=1, adv=round(font.getlength(ch)), dy=1, dx=0, bmp=b"\x00")
    l, t, r, b = font.getbbox(ch, anchor="ls")
    if r <= l or b <= t:
        return empty
    pad = 4
    img = Image.new("L", (r - l + 2 * pad, b - t + 2 * pad), 0)
    ImageDraw.Draw(img).text((pad - l, pad - t), ch, font=font, fill=255, anchor="ls")
    bb = img.getbbox()
    if not bb:
        return empty
    crop = img.crop(bb)
    return dict(u=ord(ch), w=crop.width, h=crop.height, adv=empty["adv"],
                dy=(pad - t) - bb[1], dx=bb[0] - (pad - l), bmp=crop.tobytes())


def vlw(path, size, chars):
    font = ImageFont.truetype(path, size)
    chars = sorted(set(c for c in chars if c == " " or font.getmask(c).getbbox()))
    gs = [glyph(font, c) for c in chars]
    ascent = max(g["dy"] for g in gs)
    descent = max(g["h"] - g["dy"] for g in gs)
    out = struct.pack(">6i", len(gs), 11, ascent + descent, 0, ascent, descent)
    for g in gs:
        out += struct.pack(">7i", g["u"], g["h"], g["w"], g["adv"], g["dy"], g["dx"], 0)
    return out + b"".join(g["bmp"] for g in gs)


def main():
    root = Path(__file__).resolve().parents[1]
    lines = ["// Generated by tools/make_fonts.py. Inter and DejaVu Sans Mono, SIL OFL / Bitstream Vera.",
             "#pragma once", "#include <stdint.h>", "#ifndef PROGMEM", "#define PROGMEM", "#endif", ""]
    for name, path, size, chars in FONTS:
        data = vlw(path, size, chars)
        lines.append(f"const uint8_t {name}[{len(data)}] PROGMEM = {{")
        lines += ["  " + ",".join(map(str, data[i:i + 24])) + "," for i in range(0, len(data), 24)]
        lines.append("};\n")
    (root / "src" / "fonts.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
